<?php

/**
 * Download local Tor, FireHOL anonymous, and cloud CIDR lists.
 *
 * Writes geoip/ranges/anonymous.cidr and a binary cache the click path reads.
 * A missing file leaves connection type on the ASN label (fail open).
 * This does not call paid IP APIs and does not change campaign route modes.
 *
 * Usage:
 *   php scripts/download-anonymous-ranges.php
 *   php scripts/download-anonymous-ranges.php --output=geoip/ranges
 */

declare(strict_types=1);

$options = getopt('', ['output:']);
$outputDir = isset($options['output']) && is_string($options['output']) && $options['output'] !== ''
    ? $options['output']
    : dirname(__DIR__) . DIRECTORY_SEPARATOR . 'geoip' . DIRECTORY_SEPARATOR . 'ranges';

if (!is_dir($outputDir) && !mkdir($outputDir, 0755, true) && !is_dir($outputDir)) {
    fwrite(STDERR, "Cannot create {$outputDir}\n");
    exit(1);
}

ini_set('memory_limit', '512M');

require dirname(__DIR__) . '/vendor/autoload.php';

use SimpleKuma\GeoIP\AnonymousRangeLookup;

echo "Anonymous range downloader\n";
echo "==========================\n\n";

$outFile = $outputDir . DIRECTORY_SEPARATOR . 'anonymous.cidr';
$handle = fopen($outFile . '.tmp', 'wb');
if ($handle === false) {
    fwrite(STDERR, "Cannot write {$outFile}\n");
    exit(1);
}

fwrite($handle, "# Generated by scripts/download-anonymous-ranges.php\n");
fwrite($handle, "# Tor exits, FireHOL anonymous nets, and cloud CIDRs. Not a block on its own.\n");

$written = 0;
$errors = [];

/**
 * @param resource $handle
 */
function appendCidrs($handle, string $body, int &$written): void
{
    $lines = preg_split("/\r\n|\n|\r/", $body) ?: [];
    foreach ($lines as $line) {
        $line = trim($line);
        if ($line === '' || $line[0] === '#') {
            continue;
        }
        $token = preg_split('/\s+/', $line)[0] ?? '';
        if ($token === '' || $token[0] === '!') {
            continue;
        }
        if (!str_contains($token, '/') && filter_var($token, FILTER_VALIDATE_IP) === false) {
            continue;
        }
        fwrite($handle, $token . "\n");
        $written++;
    }
}

function httpGet(string $url): string
{
    $ch = curl_init($url);
    if ($ch === false) {
        throw new RuntimeException('curl init failed');
    }
    curl_setopt_array($ch, [
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_FOLLOWLOCATION => true,
        CURLOPT_CONNECTTIMEOUT => 20,
        CURLOPT_TIMEOUT => 180,
        CURLOPT_USERAGENT => 'SimpleKuma-range-update',
        CURLOPT_SSL_VERIFYPEER => true,
    ]);
    $body = curl_exec($ch);
    $code = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
    $err = curl_error($ch);
    curl_close($ch);
    if (!is_string($body) || $code < 200 || $code >= 300) {
        throw new RuntimeException($url . ' HTTP ' . $code . ($err !== '' ? ' ' . $err : ''));
    }

    return $body;
}

$jobs = [
    'Tor exit nodes' => static function () use ($handle, &$written): void {
        appendCidrs($handle, httpGet('https://check.torproject.org/torbulkexitlist'), $written);
    },
    'FireHOL anonymous' => static function () use ($handle, &$written): void {
        appendCidrs(
            $handle,
            httpGet('https://raw.githubusercontent.com/firehol/blocklist-ipsets/master/firehol_anonymous.netset'),
            $written
        );
    },
    'AWS' => static function () use ($handle, &$written): void {
        $json = json_decode(httpGet('https://ip-ranges.amazonaws.com/ip-ranges.json'), true);
        if (!is_array($json)) {
            throw new RuntimeException('AWS JSON was not an object');
        }
        $lines = '';
        foreach ($json['prefixes'] ?? [] as $row) {
            if (is_array($row) && isset($row['ip_prefix']) && is_string($row['ip_prefix'])) {
                $lines .= $row['ip_prefix'] . "\n";
            }
        }
        foreach ($json['ipv6_prefixes'] ?? [] as $row) {
            if (is_array($row) && isset($row['ipv6_prefix']) && is_string($row['ipv6_prefix'])) {
                $lines .= $row['ipv6_prefix'] . "\n";
            }
        }
        appendCidrs($handle, $lines, $written);
    },
    'Google Cloud' => static function () use ($handle, &$written): void {
        $json = json_decode(httpGet('https://www.gstatic.com/ipranges/cloud.json'), true);
        if (!is_array($json)) {
            throw new RuntimeException('Google Cloud JSON was not an object');
        }
        $lines = '';
        foreach ($json['prefixes'] ?? [] as $row) {
            if (!is_array($row)) {
                continue;
            }
            foreach (['ipv4Prefix', 'ipv6Prefix'] as $key) {
                if (isset($row[$key]) && is_string($row[$key])) {
                    $lines .= $row[$key] . "\n";
                }
            }
        }
        appendCidrs($handle, $lines, $written);
    },
    'Azure' => static function () use ($handle, &$written): void {
        $page = httpGet('https://www.microsoft.com/en-us/download/confirmation.aspx?id=56519');
        if (!preg_match('#https://download\.microsoft\.com/[^"\']+ServiceTags_Public_[0-9]+\.json#', $page, $match)) {
            throw new RuntimeException('Azure service-tag download link was not on the confirmation page');
        }
        $json = json_decode(httpGet($match[0]), true);
        if (!is_array($json)) {
            throw new RuntimeException('Azure JSON was not an object');
        }
        $lines = '';
        foreach ($json['values'] ?? [] as $value) {
            $prefixes = $value['properties']['addressPrefixes'] ?? null;
            if (!is_array($prefixes)) {
                continue;
            }
            foreach ($prefixes as $prefix) {
                if (is_string($prefix)) {
                    $lines .= $prefix . "\n";
                }
            }
        }
        appendCidrs($handle, $lines, $written);
    },
    'DigitalOcean' => static function () use ($handle, &$written): void {
        $base = 'https://raw.githubusercontent.com/lord-alfred/ipranges/main/digitalocean/';
        appendCidrs($handle, httpGet($base . 'ipv4.txt'), $written);
        appendCidrs($handle, httpGet($base . 'ipv6.txt'), $written);
    },
    'OVH' => static function () use ($handle, &$written): void {
        $lines = '';
        foreach (['AS16276', 'AS35540'] as $asn) {
            $json = json_decode(
                httpGet('https://stat.ripe.net/data/announced-prefixes/data.json?resource=' . $asn),
                true
            );
            if (!is_array($json)) {
                throw new RuntimeException($asn . ' JSON was not an object');
            }
            foreach ($json['data']['prefixes'] ?? [] as $row) {
                if (is_array($row) && isset($row['prefix']) && is_string($row['prefix'])) {
                    $lines .= $row['prefix'] . "\n";
                }
            }
        }
        if ($lines === '') {
            throw new RuntimeException('OVH announced no prefixes');
        }
        appendCidrs($handle, $lines, $written);
    },
];

foreach ($jobs as $label => $job) {
    echo "Downloading {$label}...\n";
    $before = $written;
    try {
        $job();
        echo "  added " . ($written - $before) . " ranges\n";
    } catch (Throwable $e) {
        $errors[] = $label . ': ' . $e->getMessage();
        echo "  failed: " . $e->getMessage() . "\n";
    }
}

fclose($handle);

if ($written === 0) {
    @unlink($outFile . '.tmp');
    fwrite(STDERR, "No ranges downloaded.\n");
    foreach ($errors as $error) {
        fwrite(STDERR, "  {$error}\n");
    }
    exit(1);
}

if (!rename($outFile . '.tmp', $outFile)) {
    fwrite(STDERR, "Cannot replace {$outFile}\n");
    exit(1);
}

echo "\nWrote {$written} ranges to {$outFile}\n";
echo "Building lookup cache...\n";
if (!AnonymousRangeLookup::rebuildCache($outputDir)) {
    fwrite(STDERR, "Range file was written, but the cache rebuild failed. The next click will parse the file.\n");
}
AnonymousRangeLookup::setDirectory(null);

if ($errors !== []) {
    echo "\nFinished with some sources skipped:\n";
    foreach ($errors as $error) {
        echo "  {$error}\n";
    }
    exit(0);
}

echo "All sources downloaded.\n";
exit(0);
